// ─── SPA TAB NAVIGATION ───
function initNavigation() {
  const navLinks = document.querySelectorAll(".nav-links a");
  const tabs = document.querySelectorAll(".tab-content");
  const navCta = document.querySelector(".nav-cta");
  const heroCheckBtn = document.querySelector(".hero-actions .btn-primary");
  const heroDirBtn = document.querySelector(".hero-actions .btn-outline");

  function switchTab(tabId) {
    // Hide all tabs
    tabs.forEach(tab => tab.classList.remove("active"));
    
    // Deactivate all nav links and activate the one matching tabId
    navLinks.forEach(link => {
      link.parentElement.classList.remove("active");
      if (link.getAttribute("data-tab") === tabId) {
        link.parentElement.classList.add("active");
      }
    });

    // Activate target tab
    const targetTab = document.getElementById(tabId);
    if (targetTab) {
      targetTab.classList.add("active");
    }

    // Scroll to top of the page
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  // Bind click events on nav links
  navLinks.forEach(link => {
    link.addEventListener("click", (e) => {
      e.preventDefault();
      const tabId = link.getAttribute("data-tab");
      switchTab(tabId);
    });
  });

  // Bind click event on nav CTA (Laporkan Hoax)
  if (navCta) {
    navCta.addEventListener("click", (e) => {
      e.preventDefault();
      switchTab("report-tab");
    });
  }

  // Bind click events on hero CTAs
  if (heroCheckBtn) {
    heroCheckBtn.addEventListener("click", (e) => {
      e.preventDefault();
      switchTab("check-tab");
    });
  }

  if (heroDirBtn) {
    heroDirBtn.addEventListener("click", (e) => {
      e.preventDefault();
      switchTab("directory-tab");
    });
  }
}

// ─── FAQ ACCORDION LOGIC ───
function initFAQ() {
  const faqQuestions = document.querySelectorAll(".faq-question");
  faqQuestions.forEach(question => {
    question.addEventListener("click", () => {
      const item = question.parentElement;
      
      // Close all other items (accordion behavior)
      document.querySelectorAll(".faq-item").forEach(otherItem => {
        if (otherItem !== item) {
          otherItem.classList.remove("active");
        }
      });

      // Toggle current item
      item.classList.toggle("active");
    });
  });
}

// ─── CLICKBAIT DIRECTORY LOGIC ───
let currentFilterCategory = "Semua";
let currentSearchQuery = "";

function initDirectory() {
  const searchInput = document.getElementById("dirSearchInput");
  const filterButtons = document.querySelectorAll(".filter-btn");

  // Initial render
  renderClickbaitTable();

  // Search input event
  if (searchInput) {
    searchInput.addEventListener("input", (e) => {
      currentSearchQuery = e.target.value.toLowerCase();
      renderClickbaitTable();
    });
  }

  // Filter buttons event
  filterButtons.forEach(btn => {
    btn.addEventListener("click", () => {
      // Remove active from all
      filterButtons.forEach(b => b.classList.remove("active"));
      // Add active to clicked
      btn.classList.add("active");

      currentFilterCategory = btn.getAttribute("data-category");
      renderClickbaitTable();
    });
  });
}

function renderClickbaitTable() {
  const tbody = document.getElementById("hoaxTableBody");
  if (!tbody) return;

  tbody.innerHTML = "";

  // Filter records
  const filtered = CLICKBAIT_DATABASE.filter(item => {
    const matchesCategory = currentFilterCategory === "Semua" || item.category === currentFilterCategory;
    const matchesSearch = item.title.toLowerCase().includes(currentSearchQuery) || 
                          item.category.toLowerCase().includes(currentSearchQuery);
    return matchesCategory && matchesSearch;
  });

  if (filtered.length === 0) {
    tbody.innerHTML = `<tr><td colspan="5" style="text-align: center; color: var(--text-muted); padding: 2rem;">Tidak ada judul clickbait yang cocok dengan pencarian Anda.</td></tr>`;
    return;
  }

  filtered.forEach(item => {
    const row = document.createElement("tr");
    
    // Format badge
    const badgeClass = item.label.toLowerCase() === "clickbait" ? "clickbait" : "factual";
    
    // Format date Indonesian
    const dateObj = new Date(item.date);
    const formattedDate = dateObj.toLocaleDateString('id-ID', { day: 'numeric', month: 'short', year: 'numeric' });

    row.innerHTML = `
      <td><span class="table-badge ${badgeClass}">${item.label}</span></td>
      <td class="hoax-title-cell">${item.title}</td>
      <td><span style="color: var(--yellow); font-weight: 700;">${item.category}</span></td>
      <td style="color: var(--text-muted); font-size: 13px;">${formattedDate}</td>
      <td><a href="${item.link}" target="_blank" class="clarification-link">Link Berita ↗</a></td>
    `;
    tbody.appendChild(row);
  });
}

// ─── FORM & API HANDLERS ───
function initFormHandlers() {
  const predictInput = document.getElementById("predictInput");
  const checkBtn = document.getElementById("checkBtn");
  const loadingArea = document.getElementById("predictLoading");
  const resultCard = document.getElementById("resultCard");

  // Prediksi button click
  window.checkHeadline = async () => {
    if (!predictInput) return;
    const title = predictInput.value.trim();
    if (title.length < 5) {
      alert("Harap masukkan judul berita yang lebih lengkap (minimal 5 karakter).");
      return;
    }

    // Reset and hide loader
    if (resultCard) {
      resultCard.style.display = "none";
    }
    if (loadingArea) {
      loadingArea.style.display = "block";
    }
    if (checkBtn) {
      checkBtn.disabled = true;
    }

    try {
      const response = await fetch("/api/predict", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ title: title })
      });

      const result = await response.json();
      
      if (loadingArea) loadingArea.style.display = "none";
      if (checkBtn) checkBtn.disabled = false;

      if (result.status === "success") {
        displayPredictionResult(result);
      } else {
        alert("Gagal melakukan prediksi: " + result.message);
      }
    } catch (err) {
      if (loadingArea) loadingArea.style.display = "none";
      if (checkBtn) checkBtn.disabled = false;
      console.error(err);
      alert("Terjadi kesalahan koneksi saat mengirim permintaan ke server.");
    }
  };

  // Report form handler
  const reportForm = document.getElementById("reportForm");
  const reportAlert = document.getElementById("reportSuccessAlert");
  const reportRef = document.getElementById("reportRefCode");

  if (reportForm) {
    reportForm.addEventListener("submit", async (e) => {
      e.preventDefault();
      
      const formData = new FormData(reportForm);
      try {
        const response = await fetch("/api/report", {
          method: "POST",
          body: formData
        });

        const result = await response.json();
        if (result.status === "success") {
          // Show alert & ref code
          if (reportRef) reportRef.textContent = result.report_id;
          if (reportAlert) reportAlert.style.display = "block";
          
          // Reset form
          reportForm.reset();

          // Scroll alert into view
          if (reportAlert) {
            reportAlert.scrollIntoView({ behavior: "smooth", block: "nearest" });
          }
        } else {
          alert("Gagal mengirim laporan: " + result.message);
        }
      } catch (err) {
        console.error(err);
        alert("Terjadi kesalahan saat mengirim laporan ke server.");
      }
    });
  }
}

// ─── VISUALIZE DETECTOR RESULTS ───
function displayPredictionResult(data) {
  const resultCard = document.getElementById("resultCard");
  const resVerdictBadge = document.getElementById("resVerdictBadge");
  const resScoreText = document.getElementById("resScoreText");
  const resMetaDesc = document.getElementById("resMetaDesc");

  const barClickbait = document.getElementById("barClickbait");
  const valClickbait = document.getElementById("valClickbait");
  
  const barEmotion = document.getElementById("barEmotion");
  const valEmotion = document.getElementById("valEmotion");
  
  const barSource = document.getElementById("barSource");
  const valSource = document.getElementById("valSource");
  
  const barFact = document.getElementById("barFact");
  const valFact = document.getElementById("valFact");

  if (!resultCard) return;

  // Show panel
  resultCard.style.display = "block";

  // Dynamic calculations based on probability
  const probPercent = Math.round(data.probability * 100);
  const heuristics = data.heuristics;

  // Calculate emotion/exaggeration score based on capital letters and punctuation
  let emotionScore = 0;
  if (heuristics.exclamation_count > 0) emotionScore += 35 * heuristics.exclamation_count;
  if (heuristics.question_count > 0) emotionScore += 20 * heuristics.question_count;
  if (heuristics.ellipsis_count > 0) emotionScore += 15;
  emotionScore += Math.round(heuristics.caps_ratio * 100);
  emotionScore = Math.min(95, Math.max(10, emotionScore)); // limit between 10-95%
  
  // Calculate objectivity score
  const objectivityScore = 100 - probPercent;

  // Calculate credibility score
  let credibilityScore = 0;
  if (data.verdict === "CLICKBAIT") {
    credibilityScore = Math.max(8, Math.round(100 - (data.probability * 85)));
  } else {
    credibilityScore = Math.min(98, Math.round(75 + ((1.0 - data.probability) * 23)));
  }

  const isClickbait = data.verdict === "CLICKBAIT";
  if (resVerdictBadge) {
    resVerdictBadge.textContent = isClickbait ? "CLICKBAIT 🔴" : "FAKTUAL 🟢";
    resVerdictBadge.className = isClickbait ? "verdict-badge clickbait" : "verdict-badge faktual";
  }
  
  if (resScoreText) {
    resScoreText.innerHTML = `${data.confidence}% <small>kepercayaan</small>`;
  }

  let kwText = "";
  if (heuristics.has_clickbait_keywords) {
    kwText = ` Judul menggunakan kata kunci pemancing: <strong>${heuristics.matched_keywords.join(', ')}</strong>.`;
  }
  
  let summary = "";
  if (isClickbait) {
    summary = `Judul berita terindikasi kuat sebagai clickbait karena menggunakan kalimat provokatif untuk menarik perhatian.${kwText}`;
  } else {
    summary = `Judul berita tergolong informatif, objektif, dan faktual. Tidak ditemukan indikasi manipulasi clickbait yang signifikan.`;
  }
  if (resMetaDesc) {
    resMetaDesc.innerHTML = summary;
  }

  // Animate progress bars
  setTimeout(() => {
    if (barClickbait) barClickbait.style.width = `${probPercent}%`;
    if (valClickbait) valClickbait.textContent = `${probPercent}%`;

    if (barEmotion) barEmotion.style.width = `${emotionScore}%`;
    if (valEmotion) valEmotion.textContent = `${emotionScore}%`;

    if (barSource) barSource.style.width = `${credibilityScore}%`;
    if (valSource) valSource.textContent = `${credibilityScore}%`;

    if (barFact) barFact.style.width = `${objectivityScore}%`;
    if (valFact) valFact.textContent = `${objectivityScore}%`;
  }, 100);

  // Scroll result into view
  setTimeout(() => resultCard.scrollIntoView({ behavior: "smooth", block: "nearest" }), 150);
}

// Utility to fill check text from recommendations
window.fillSearch = (el) => {
  const predictInput = document.getElementById("predictInput");
  if (predictInput) {
    predictInput.value = el.textContent.trim();
    predictInput.focus();
  }
};
